import { createRequire } from 'node:module'
const require = createRequire('file:///C:/Users/ramac/.claude/skills/gstack/node_modules/')
const { chromium } = require('playwright')
const b = await chromium.launch({ args: ['--enable-gpu', '--use-angle=d3d11', '--ignore-gpu-blocklist'] })
const ctx = await b.newContext({ viewport: { width: 1280, height: 800 } })
const p = await ctx.newPage()
p.on('pageerror', (e) => console.log('pageerror', e.message))
await p.goto('http://localhost:3003/entidad/tropical-poncho?red=tropical-poncho&perf=1&semilla=nav2', { timeout: 120000 })
await p.waitForFunction(() => window.__sinapsis && document.querySelector('.cargando--fuera'), null, { timeout: 120000 })
await p.waitForTimeout(3000)
const ents = () => p.evaluate(() => ({ has: 'navigation' in window, idx: navigation.currentEntry.index, urls: navigation.entries().map((e) => e.url.replace(location.origin, '')), state: history.state && JSON.stringify(history.state).slice(0, 80) }))
console.log('inicio', JSON.stringify(await ents()))
// navegar con la UI: elegir un area del menu superior, luego un nodo
const areas = await p.locator('.nav-item').allTextContents(); console.log('areas', areas)
await p.locator('.nav-item').nth(1).click(); await p.waitForTimeout(3500)
console.log('tras area', JSON.stringify(await ents()))
await p.locator('.nav-item').nth(0).click(); await p.waitForTimeout(3500)
console.log('tras area2', JSON.stringify(await ents()))
// entrar en un nodo desde el menu lateral si hay
const lat = await p.locator('.lateralFloatingMenu button').count(); console.log('lateral botones', lat)
// traverseTo / history.go(-2)
await p.evaluate(() => history.go(-2)); await p.waitForTimeout(3500)
console.log('tras go(-2)', JSON.stringify(await ents()), p.url())
await p.evaluate(() => navigation.traverseTo(navigation.entries()[navigation.entries().length - 1].key)); await p.waitForTimeout(3500)
console.log('tras traverseTo ultimo', JSON.stringify(await ents()), p.url())
await p.reload(); await p.waitForTimeout(4000)
console.log('tras reload', JSON.stringify(await ents()))
await b.close()
